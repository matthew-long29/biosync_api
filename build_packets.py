#!/usr/bin/env python3
"""
Desktop front end for pico/biosync_packet.py: writes packets.mem for packet_tx.sv ($readmemh, one
112-bit frame = 28 hex digits per line, packet 0 first).

    python build_packets.py                    # interactive (temporary): prompts for every field
                                               # like gen_packet.py, appends to packets.mem
    python build_packets.py build smoke        # a function of pico/sequences.py -> packets.mem
    python build_packets.py show               # decode an existing packets.mem

The sequences in pico/sequences.py are the same ones the Pico sends with run("smoke").

Options:  --mem PATH (default: <repo>/packets.mem)   --sv DIR  (build: also write one .sv
localparam per packet, as gen_packet.py does, for the testbenches)

packet_tx.sv's NUM_PACKETS parameter must equal the number of lines; build/add print it.
"""

import argparse
import os
import sys

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(SCRIPT_DIR, "pico"))     # the Pico code doubles as the desktop API

import biosync_defs as D                     # noqa: E402
import biosync_packet as bp                  # noqa: E402

DEFAULT_MEM = os.path.normpath(os.path.join(SCRIPT_DIR, "..", "..", "packets.mem"))


def read_mem(path):
    if not os.path.exists(path):
        return []
    lines = []
    with open(path) as f:
        for raw in f:
            line = raw.split("//")[0].strip()
            if line and not line.startswith("@"):
                lines.append(line)
    return lines


def write_mem(path, packets):
    with open(path, "w", newline="\n") as f:
        for p in packets:
            f.write(p.hex() + "\n")


def print_table(packets):
    for i, p in enumerate(packets):
        print("%3d  %s  %s" % (i, p.hex(), p.summary()))
        for w in p.warnings():
            print("          NOTE: %s" % w)


def load_sequence(name):
    import sequences
    fn = getattr(sequences, name, None)
    if not callable(fn) or name in ("ms", "us"):
        names = [n for n in dir(sequences) if not n.startswith("_") and n not in ("ms", "us")]
        sys.exit("pico/sequences.py has no sequence %r (available: %s)" % (name, ", ".join(names)))
    return fn


def write_sv(dirname, packets, seqfile):
    os.makedirs(dirname, exist_ok=True)
    for i, p in enumerate(packets):
        name = "PKT_%02d_%s_SEQ%d" % (i, p.cmd, p.seq)
        with open(os.path.join(dirname, name.lower() + ".sv"), "w", newline="\n") as f:
            f.write("// Generated by build_packets.py from %s\n" % ("sequences." + seqfile))
            f.write("// %s\n" % p.summary())
            for w in p.warnings():
                f.write("// NOTE: %s\n" % w)
            f.write("// full frame (with CRC): %d'h%s\n" % (D.PACKET_SIZE, p.hex()))
            f.write("localparam logic [%d:0] %s = %s;\n" % (bp.HEAD_SIZE - 1, name, p.sv_literal()))


def cmd_build(args):
    s = bp.Session()
    load_sequence(args.sequence)(s)
    if not s.history:
        sys.exit("sequence produced no packets")
    write_mem(args.mem, s.history)
    print_table(s.history)
    if args.sv:
        write_sv(args.sv, s.history, args.sequence)
        print("\n.sv localparams written to %s" % os.path.normpath(args.sv))
    print("\nWrote %d packets to %s  (set packet_tx NUM_PACKETS = %d)"
          % (len(s.history), args.mem, len(s.history)))


def cmd_show(args):
    lines = read_mem(args.mem)
    pkts = []
    for i, line in enumerate(lines):
        try:
            pkts.append(bp.Packet.decode(line, check_crc=False))
        except (bp.PacketError, ValueError) as e:
            print("%3d  %s  ! %s" % (i, line, e))
    print_table(pkts)
    print("\n%d packets in %s" % (len(lines), args.mem))


# ------------------------------------------------------------------------------------------------
# Interactive mode (TEMPORARY): same prompts as gen_packet.py, but the packets go to packets.mem.
# Reuses gen_packet.py's ask()/ask_value() and its COMMAND_DOC / FIELD_DOC help texts.
# ------------------------------------------------------------------------------------------------

def _ask_yes(gp, prompt, default):
    s = gp.ask("%s [%s] > " % (prompt, "Y/n" if default else "y/N")).strip().lower()
    return default if s == "" else s in ("y", "yes")


def _ask_command(gp, names):
    print("\nAvailable commands:")
    for n in names:
        print("  0x%X  %-15s %s" % (D.OPCODES[n], n, gp.COMMAND_DOC.get("OP_" + n, "")))
    while True:
        s = gp.ask("\nWhich command do you want to send? (opcode, e.g. 5 / 0xA, or name; "
                   "'done' to finish) > ").strip().upper()
        if s in ("DONE", "Q", "QUIT", "EXIT"):
            return None
        for n in names:
            if s in (n, "OP_" + n, "%X" % D.OPCODES[n], "0X%X" % D.OPCODES[n]):
                return n
        print("  ! unknown command '%s'" % s)


def _field_table(gp, p):
    """Field / bit range / value table, like the header gen_packet.py writes into its .sv files."""
    rows = [("seq", D.SEQ_SIZE, "int", p.seq), ("slave_fwd", D.SLAVE_FWD_SIZE, "bool", p.slave_fwd),
            ("opcode", D.OPCODE_SIZE, "int", p.opcode)]
    if p.layout:
        rows += [(n, w, k, 0 if k == "pad" else p.fields[n]) for n, w, k, _ in p.layout]
    else:
        rows.append(("datafield (unused)", D.DATAFIELD_SIZE, "int", 0))
    rows.append(("crc16", D.CRC_SIZE, "int", p.crc))
    lines = ["  %-28s %-10s %s" % ("field", "bits", "value")]
    bit = D.PACKET_SIZE
    for name, width, kind, v in rows:
        msb, lsb = bit - 1, bit - width
        bit = lsb
        rng = "[%d]" % msb if width == 1 else "[%d:%d]" % (msb, lsb)
        val = "0 (padding)" if kind == "pad" else gp.describe_value(kind, v, width)
        lines.append("  %-28s %-10s %s" % (name, rng, val))
    return lines


def _ask_packet(gp, cmd, next_seq):
    print("\n--> %s (opcode 0x%X)" % (cmd, D.OPCODES[cmd]))
    seq = gp.ask_value("seq", D.SEQ_SIZE, "int",
                       "Sequence number. The radio drops a packet whose seq equals the previous one "
                       "(duplicate) and ACKs it with DUP. Default = previous packet + 1.",
                       next_seq, bp.SEQ_MAX)
    fwd = gp.ask_value("slave_fwd", D.SLAVE_FWD_SIZE, "bool",
                       "1 = forward this command to the downstream slave chip instead of executing it here.",
                       0, 1)

    fields = {}
    layout = D.DATAFIELDS.get(cmd, ())
    if not layout:
        print("\n%s has no datafield; all %d datafield bits are 0." % (cmd, D.DATAFIELD_SIZE))
    else:
        sname = cmd.lower() + "_datafield_t"
        print("\nDatafield %s (%d bits):" % (sname, D.DATAFIELD_SIZE))
        for name, width, kind, vmax in layout:
            if kind == "pad":
                continue
            doc = gp.field_doc(sname, name)[1]
            default = D.CONF_RST_DEFAULTS[name] if cmd == "CONF_RST" else 0
            fields[name] = gp.ask_value(name, width, kind, doc, default, vmax)

    corrupt = gp.ask_value("corrupt CRC", 1, "bool",
                           "1 = flip one frame bit after the CRC is computed, to test that the chip "
                           "ACKs with CRC error and does not execute the command.", 0, 1)
    p = bp.Packet(cmd, seq, fwd, **fields)
    if corrupt:
        b = gp.ask_value("corrupt_bit", 7, "int", "Frame bit to flip (0 = CRC LSB, %d = seq MSB)."
                         % (D.PACKET_SIZE - 1), 0, D.PACKET_SIZE - 1)
        p = p.corrupted(b)
    return p


def cmd_interactive(args):
    import gen_packet as gp

    names = sorted(D.OPCODES, key=lambda n: D.OPCODES[n])
    print("=" * 78)
    print(" BIOSYNC packet builder -> %s" % args.mem)
    print(" Press <Enter> to accept a default.  'done' at the command prompt to finish.  Ctrl-C to abort.")
    print("=" * 78)

    existing = read_mem(args.mem)
    keep = []
    if existing:
        print("\n%s already holds %d packet(s):" % (args.mem, len(existing)))
        for i, line in enumerate(existing):
            try:
                print("  %3d  %s  %s" % (i, line, bp.Packet.decode(line, check_crc=False).summary()))
            except (bp.PacketError, ValueError) as e:
                print("  %3d  %s  ! %s" % (i, line, e))
        if _ask_yes(gp, "\nAppend to them? (n = start a new file)", True):
            keep = existing
    next_seq = 1
    if keep:
        try:
            next_seq = (bp.Packet.decode(keep[-1], check_crc=False).seq + 1) & bp.SEQ_MAX
        except (bp.PacketError, ValueError):
            pass

    new = []
    while True:
        cmd = _ask_command(gp, names)
        if cmd is None:
            break
        p = _ask_packet(gp, cmd, next_seq)

        print("\nPacket %d: %s" % (len(keep) + len(new), p.summary()))
        print("\n".join(_field_table(gp, p)))
        print("  frame hex: %s" % p.hex())
        for w in p.warnings():
            print("  NOTE: %s" % w)
        if p.cmd == "CONF_RST" and p.fields["wakeup_code"] != D.WAKEUP_CODE_DEF:
            print("  NOTE: packet_tx.sv sends a fixed WAKEUP_CODE parameter; the chip will ignore every "
                  "later packet unless you change it.")

        if _ask_yes(gp, "\nKeep this packet?", True):
            new.append(p)
            next_seq = (p.seq + 1) & bp.SEQ_MAX
            # rewrite after every packet so Ctrl-C never loses accepted packets
            with open(args.mem, "w", newline="\n") as f:
                f.write("".join(line + "\n" for line in keep + [q.hex() for q in new]))
            print("  -> saved (%d packets in file)" % (len(keep) + len(new)))
        else:
            print("  -> discarded")
        if not _ask_yes(gp, "\nAdd another packet?", True):
            break

    total = len(keep) + len(new)
    if not new:
        print("\nNo packets added; %s unchanged." % args.mem)
        return
    print("\n%s now holds %d packets:" % (args.mem, total))
    cmd_show(args)
    print("Set packet_tx NUM_PACKETS = %d." % total)


def main():
    ap = argparse.ArgumentParser(description="Build packets.mem for packet_tx.sv")
    ap.add_argument("--mem", default=DEFAULT_MEM, help="packets.mem path (default %(default)s)")
    sub = ap.add_subparsers(dest="action")
    b = sub.add_parser("build", help="build a sequence from pico/sequences.py, overwrite --mem")
    b.add_argument("sequence", help="function name in pico/sequences.py, e.g. smoke")
    b.add_argument("--sv", metavar="DIR", help="also write one .sv localparam per packet")
    sub.add_parser("interactive", aliases=["add"],
                   help="prompt for packets field by field (default when no action is given)")
    sub.add_parser("show", help="decode --mem")
    args = ap.parse_args()
    actions = {"build": cmd_build, "show": cmd_show, "interactive": cmd_interactive, "add": cmd_interactive}
    actions.get(args.action or "interactive")(args)


if __name__ == "__main__":
    try:
        main()
    except KeyboardInterrupt:
        print()
        sys.exit("Aborted.")
    except bp.PacketError as e:
        sys.exit("ERROR: %s" % e)
