#!/usr/bin/env python3
"""
Generate biosync_defs.py from default_settings_packet_structs_pkg.sv.

biosync_packet.py (the packet API) must also run under MicroPython on the Raspberry Pi Pico /
the radio dongle, where we can neither ship the RTL nor parse SystemVerilog. So the package is
parsed here on the desktop (with the same parser gen_packet.py uses) and flattened into plain
Python constants that biosync_packet.py imports.

Re-run this whenever the package changes, then upload the pico/ folder to the Pico again:

    python gen_biosync_defs.py [--pkg PATH] [--out pico/biosync_defs.py]
"""

import argparse
import os
import sys

import gen_packet as gp

OUT_DEFAULT = os.path.join(gp.SCRIPT_DIR, "pico", "biosync_defs.py")

# Package localparams copied verbatim into biosync_defs.py (if present).
SCALARS = [
    "PACKET_SIZE", "SEQ_SIZE", "SLAVE_FWD_SIZE", "OPCODE_SIZE", "DATAFIELD_SIZE", "CRC_SIZE",
    "WAKEUP_CODE_SIZE", "WAKEUP_CODE_DEF",
    "ACK_STATUS_SIZE", "ACK_SIZE", "ACK_STATUS_OK", "ACK_STATUS_CRC", "ACK_STATUS_DUP", "ACK_STATUS_DONE",
    "DATA_PREAMBLE_STATUS_SIZE", "DATA_PREAMBLE_SIZE", "DATA_PREAMBLE_STATUS",
    "SPAD_M", "SPAD_BITS", "SPAD_ROWS_MACRO", "SPAD_COLS_MACRO",
]


def build(pkg_path):
    params, structs, opcodes = gp.parse_package(pkg_path)
    head_w = params["SEQ_SIZE"] + params["SLAVE_FWD_SIZE"] + params["OPCODE_SIZE"] + params["DATAFIELD_SIZE"]
    if head_w + params["CRC_SIZE"] != params["PACKET_SIZE"]:
        sys.exit("ERROR: PACKET_SIZE does not match the sum of its parts in the package.")

    out = []
    out.append('"""')
    out.append("AUTO-GENERATED by gen_biosync_defs.py from default_settings_packet_structs_pkg.sv.")
    out.append("Do not edit by hand: change the package and re-run gen_biosync_defs.py.")
    out.append("")
    out.append("Plain constants only, so this file also imports under MicroPython.")
    out.append('"""')
    out.append("")
    for name in SCALARS:
        if name in params:
            v = params[name]
            is_code = name.endswith("_DEF") or ("STATUS" in name and not name.endswith("_SIZE"))
            out.append("%s = %s" % (name, "0x%X" % v if is_code else str(v)))
    out.append("")
    out.append("CLK_HZ = %d  # clk_32k: unit of every 'time' field" % gp.CLK_HZ)
    out.append("")

    out.append("# command name -> opcode")
    out.append("OPCODES = {")
    for val, name in opcodes:
        out.append('    "%s": 0x%X,' % (name[3:], val))
    out.append("}")
    out.append("")

    out.append("# command name -> datafield layout, MSB first: (field, width, kind, max_value)")
    out.append("#   kind: int | time (clk_32k cycles) | mask (bit i = row/col i) | bool | pad")
    out.append("# Commands missing here have no datafield (all zeros).")
    out.append("DATAFIELDS = {")
    for val, name in opcodes:
        sname = gp.struct_for_opcode(name, structs)
        if sname is None:
            continue
        fields = structs[sname]
        total = sum(w for _, w in fields)
        if total != params["DATAFIELD_SIZE"]:
            sys.exit("ERROR: %s is %d bits, DATAFIELD_SIZE is %d." % (sname, total, params["DATAFIELD_SIZE"]))
        out.append('    "%s": (' % name[3:])
        for fname, width in fields:
            if fname.startswith("padding"):
                kind = "pad"
            else:
                kind = gp.field_doc(sname, fname)[0] or ("bool" if width == 1 else "int")
            vmax = (1 << width) - 1
            if fname in gp.FIELD_MAX:
                lim = gp.FIELD_MAX[fname]
                vmax = min(vmax, params[lim] if isinstance(lim, str) else lim)
            out.append('        ("%s", %d, "%s", %d),' % (fname, width, kind, vmax))
        out.append("    ),")
    out.append("}")
    out.append("")

    out.append("# CONF_RST rewrites every register, so unspecified fields take the package reset values.")
    out.append("CONF_RST_DEFAULTS = {")
    conf = gp.struct_for_opcode("OP_CONF_RST", structs)
    for fname, _ in structs.get(conf, []):
        if not fname.startswith("padding"):
            out.append('    "%s": 0x%X,' % (fname, gp.field_default(fname, params)))
    out.append("}")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.strip().splitlines()[0])
    ap.add_argument("--pkg", default=gp.DEFAULT_PKG)
    ap.add_argument("--out", default=OUT_DEFAULT)
    args = ap.parse_args()
    text = build(args.pkg)
    with open(args.out, "w", newline="\n") as f:
        f.write(text)
    print("Written %s" % os.path.normpath(args.out))


if __name__ == "__main__":
    main()
